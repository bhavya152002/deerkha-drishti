# app/routers/dashboard.py -> up 3 = server/ ; templates live at server/templates
_server_dir = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
_templates_dir = os.path.join(_server_dir, "templates")
templates = Jinja2Templates(directory=_templates_dir)

# THREE routers, deliberately, because they need three different auth answers.
#
# This used to be one router where every page handler called an inline
# _page() helper that checked the session itself. That is opt-in security: a
# handler that forgets the call is silently public, and nothing catches it --
# not review, not tests, not runtime. The guard now lives on the router, so a
# new page is protected by default and you would have to actively move it to
# `public_router` to expose it. tests/test_route_auth.py enforces this.
public_router = APIRouter(tags=["auth"])
router = APIRouter(tags=["dashboard"], dependencies=[Depends(require_admin_page)])
api_router = APIRouter(tags=["dashboard-api"], dependencies=[Depends(require_admin)])

# Filenames are generated by upload_reference_frame() as
# "<camera-uuid>_<8 hex>.<ext>", never taken from the client. Anything else is
# not one of ours.
_SAFE_FRAME_NAME = re.compile(r"[A-Za-z0-9._-]{1,128}")


@public_router.get("/login", response_class=HTMLResponse)
def login_page(request: Request):
    return templates.TemplateResponse("login.html", {"request": request, "error": None})


@public_router.post("/login")
def login_submit(request: Request, username: str = Form(...), password: str = Form(...)):
    if verify_admin_login(username, password):
        request.session["admin_user"] = username
        return RedirectResponse("/", status_code=303)
    # Deliberately generic: never reveal whether the username exists.
    return templates.TemplateResponse("login.html", {"request": request, "error": "Invalid credentials"}, status_code=401)


@public_router.get("/logout")
def logout(request: Request):
    request.session.clear()
    return RedirectResponse("/login", status_code=303)


def _page(request: Request, name: str, ctx: dict | None = None):
    """Render a dashboard template. Auth is already guaranteed by the router
    dependency, so this only assembles context."""
    base = {"request": request, "admin_user": request.session.get("admin_user", "")}
    base.update(ctx or {})
    return templates.TemplateResponse(name, base)


