# Cap the upload. `await file.read()` pulls the whole body into memory, so
# without a limit a single request is both an unbounded disk write and an
# unbounded RSS spike. A camera still is a few hundred KB.
MAX_REFERENCE_FRAME_BYTES = 8 * 1024 * 1024


# ---- reference-frame upload for the ROI editor (multipart, admin only) ----
@api_router.post("/api/admin/cameras/{cam_id}/reference-frame")
async def upload_reference_frame(
    cam_id: str,
    file: UploadFile = File(...),
    admin: str = Depends(require_admin),
    db: Session = Depends(get_db),
):
    import uuid as uuidlib
    try:
        cam = db.get(models.Camera, uuidlib.UUID(cam_id))
    except (ValueError, TypeError):
        cam = None
    if cam is None:
        raise HTTPException(404, "camera not found")

    ext = os.path.splitext(file.filename or "")[1].lower() or ".jpg"
    if ext not in (".jpg", ".jpeg", ".png"):
        raise HTTPException(400, "only jpg/png allowed")
    body = await file.read(MAX_REFERENCE_FRAME_BYTES + 1)
    if len(body) > MAX_REFERENCE_FRAME_BYTES:
        raise HTTPException(413, "reference frame too large (max 8 MB)")

    fname = f"{cam_id}_{secrets.token_hex(4)}{ext}"
    dest = os.path.join(settings.REFERENCE_FRAME_DIR, fname)
    with open(dest, "wb") as f:
        f.write(body)
    # Store the BARE FILENAME, not a URL path. These used to be served by an
    # unauthenticated StaticFiles mount, so the stored value was a public URL.
    # Serving is now an authenticated route, and keeping only the filename means
    # the serving path can change without rewriting every row.
    cam.reference_frame_url = fname
    db.commit()
    bump_and_audit(db, cam.device_id, actor=admin, table_name="cfg_cameras", row_pk=cam_id, action="reference-frame")
    return {"ok": True, "reference_frame_url": f"/api/admin/reference-frame/{fname}"}


@api_router.get("/api/admin/reference-frame/{fname}")
def get_reference_frame(fname: str, admin: str = Depends(require_admin)):
    """Serve an uploaded reference frame to an authenticated admin.

    Replaces `app.mount("/reference_frames", StaticFiles(...))`, which served
    operator-uploaded stills of EVERY customer's land to anyone who could guess
    a filename. An unguessable URL is not authorization, and it stops being even
    obscure the moment the dashboard is on a public domain.
    """
    # Reject anything that isn't a plain filename before touching the path, so
    # `..%2f..%2fetc%2fpasswd` cannot walk out of the data directory. The
    # realpath containment check below is the backstop.
    if not _SAFE_FRAME_NAME.fullmatch(fname):
        raise HTTPException(404, "not found")
    base = os.path.realpath(settings.REFERENCE_FRAME_DIR)
    path = os.path.realpath(os.path.join(base, fname))
    if os.path.commonpath([base, path]) != base or not os.path.isfile(path):
        raise HTTPException(404, "not found")
    return FileResponse(path, headers={"Cache-Control": "private, max-age=300"})
